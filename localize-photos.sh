#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# localize-photos.sh
# Take the Google-Drive links in js/data.js, download any image that isn't
# already in photos/, optimize it, and rewrite js/data.js to use the local
# copies. Run this after replacing js/data.js with a fresh admin export.
#   usage:  bash localize-photos.sh
# ---------------------------------------------------------------------------
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p photos

echo "1/4  collecting image ids from js/data.js…"
node -e '
global.window={}; require("./js/data.js"); const d=window.PORTFOLIO_DATA;
const ids=new Set();
const grab=u=>{ if(!u) return; const m=String(u).match(/\/file\/d\/([A-Za-z0-9_-]+)/)||String(u).match(/[?&]id=([A-Za-z0-9_-]+)/); if(m) ids.add(m[1]); };
grab(d.meta&&d.meta.coverPhoto);
(d.chapters||[]).forEach(c=>(c.photos||[]).forEach(p=>grab(p.src)));
require("fs").writeFileSync("/tmp/portfo_ids.txt",[...ids].join("\n"));
console.log("     referenced images:", ids.size);
'

echo "2/4  downloading any new images…"
NEW=/tmp/portfo_new.txt; : > "$NEW"
while read -r id; do
  [ -z "$id" ] && continue
  [ -s "photos/$id.jpg" ] && continue
  for a in 1 2 3 4; do
    code=$(curl -sL --max-time 40 -o "photos/$id.jpg" -w "%{http_code}" "https://drive.google.com/thumbnail?id=$id&sz=w1200" || true)
    if [ "$code" = "200" ] && [ -s "photos/$id.jpg" ] && file -b --mime-type "photos/$id.jpg" | grep -q '^image/'; then
      echo "photos/$id.jpg" >> "$NEW"; break
    fi
    rm -f "photos/$id.jpg"; sleep $((a*2))
  done
  [ -s "photos/$id.jpg" ] || echo "     FAILED $id"
done < /tmp/portfo_ids.txt
echo "     new downloads: $(wc -l < "$NEW" | tr -d ' ')"

if [ -s "$NEW" ]; then
  echo "3/4  optimizing new images…"
  python3 - "$NEW" <<'PY'
import sys
from PIL import Image, ImageOps
for f in open(sys.argv[1]).read().split():
    try:
        im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")
        w, h = im.size; m = max(w, h)
        if m > 1080:
            s = 1080 / m; im = im.resize((round(w*s), round(h*s)), Image.LANCZOS)
        im.save(f, "JPEG", quality=80, optimize=True)
    except Exception as e:
        print("     skip", f, e)
PY
else
  echo "3/4  no new images to optimize."
fi

echo "4/4  rewriting js/data.js to local paths…"
node -e '
const fs=require("fs");
global.window={}; require("./js/data.js"); const d=window.PORTFOLIO_DATA;
const toLocal=u=>{ if(!u) return u; const m=String(u).match(/\/file\/d\/([A-Za-z0-9_-]+)/)||String(u).match(/[?&]id=([A-Za-z0-9_-]+)/); if(m&&fs.existsSync("photos/"+m[1]+".jpg")) return "photos/"+m[1]+".jpg"; return u; };
if(d.meta) d.meta.coverPhoto=toLocal(d.meta.coverPhoto);
(d.chapters||[]).forEach(c=>(c.photos||[]).forEach(p=>{ if(p.src) p.src=toLocal(p.src); }));
if(!d.meta) d.meta={}; d.meta.rev=Date.now();   // bump revision so browsers re-sync
fs.writeFileSync("js/data.js","/* Portfolio content. Generated by admin.html. */\nwindow.PORTFOLIO_DATA = "+JSON.stringify(d,null,2)+";\n");
const left=(JSON.stringify(d).match(/drive\.google/g)||[]).length;
console.log("     done. remaining drive links:", left);
'
echo "All set. Review, then: git add -A && git commit && git push"
